export const REPORT_LABELS: Record<ReportLocale, Record<ReportLabelKey, string>> = { en, ar };

export function label(locale: ReportLocale, key: ReportLabelKey, params?: Record<string, string | number>): string {
  const t = REPORT_LABELS[locale][key] ?? en[key];
  return params ? t.replace(/\{(\w+)\}/g, (w, n: string) => (n in params ? String(params[n]) : w)) : t;
}

/** Looks up a label by a dynamic prefix (e.g. "status." + value). Unknown values are shown as-is. */
export function labelOrRaw(locale: ReportLocale, prefix: string, value: string): string {
  const key = `${prefix}.${value}` as ReportLabelKey;
  return key in en ? label(locale, key) : value;
}
